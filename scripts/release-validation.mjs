import fs from "node:fs";
import path from "node:path";

const STRICT_VERSION = /^\d+\.\d+\.\d+$/;
const PLUGIN_ID = /^[a-z]+(?:-[a-z]+)*$/;
const BASIC_LATIN_PRINTABLE = /^[\x20-\x7E]+$/;

export function readJsonFile(filePath) {
  try {
    return JSON.parse(fs.readFileSync(filePath, "utf8"));
  } catch (error) {
    const detail = error instanceof Error ? error.message : String(error);
    throw new Error(`Could not read valid JSON from ${filePath}: ${detail}`);
  }
}

export function validateReleaseMetadata({ manifest, versions, pkg }) {
  const errors = [];

  if (!isPlainObject(manifest)) return ["manifest.json must contain a JSON object."];

  requireString(manifest, "id", errors);
  requireString(manifest, "name", errors);
  requireString(manifest, "version", errors);
  requireString(manifest, "minAppVersion", errors);
  requireString(manifest, "description", errors);
  requireString(manifest, "author", errors);
  if (typeof manifest.isDesktopOnly !== "boolean") {
    errors.push("manifest.isDesktopOnly must be a boolean.");
  }

  if (typeof manifest.id === "string") {
    if (!PLUGIN_ID.test(manifest.id)) {
      errors.push("manifest.id must contain only lowercase letters separated by single hyphens.");
    }
    if (manifest.id.includes("obsidian")) errors.push("manifest.id must not contain 'obsidian'.");
    if (manifest.id.endsWith("plugin")) errors.push("manifest.id must not end with 'plugin'.");
  }

  if (typeof manifest.name === "string") {
    if (!BASIC_LATIN_PRINTABLE.test(manifest.name)) errors.push("manifest.name must use printable Basic Latin characters only.");
    if (!/^[A-Za-z0-9 ()+\-]+$/.test(manifest.name)) errors.push("manifest.name may only use letters, numbers, spaces, hyphens, plus signs, and parentheses.");
    if (/obsidian/i.test(manifest.name)) errors.push("manifest.name must not contain 'Obsidian'.");
    if (/\bplugin\b/i.test(manifest.name)) errors.push("manifest.name must not contain the word 'Plugin'.");
  }

  if (typeof manifest.version === "string" && !STRICT_VERSION.test(manifest.version)) {
    errors.push("manifest.version must use strict x.y.z format.");
  }
  if (typeof manifest.minAppVersion === "string" && !STRICT_VERSION.test(manifest.minAppVersion)) {
    errors.push("manifest.minAppVersion must use strict x.y.z format.");
  }

  if (typeof manifest.description === "string") {
    if (manifest.description.length > 250) errors.push("manifest.description must be 250 characters or fewer.");
    if (!manifest.description.endsWith(".")) errors.push("manifest.description must end with a period.");
  }

  if (manifest.authorUrl !== undefined && !isHttpUrl(manifest.authorUrl)) {
    errors.push("manifest.authorUrl must be an http(s) URL when present.");
  }
  if (manifest.fundingUrl !== undefined) validateFundingUrl(manifest.fundingUrl, errors);

  if (!isPlainObject(pkg)) {
    errors.push("package.json must contain a JSON object.");
  } else {
    if (pkg.version !== manifest.version) errors.push("package.json version must exactly match manifest.version.");
    if (pkg.main !== "main.js") errors.push("package.json main must be 'main.js'.");
    if (pkg.type !== "module") errors.push("package.json type must be 'module' for this source repository.");
    if (pkg.private !== true) errors.push("package.json must remain private because the plugin is released through GitHub, not npm.");
  }

  if (!isPlainObject(versions)) {
    errors.push("versions.json must contain a JSON object.");
  } else {
    for (const [pluginVersion, appVersion] of Object.entries(versions)) {
      if (!STRICT_VERSION.test(pluginVersion)) errors.push(`versions.json key ${JSON.stringify(pluginVersion)} must use x.y.z format.`);
      if (typeof appVersion !== "string" || !STRICT_VERSION.test(appVersion)) {
        errors.push(`versions.json value for ${JSON.stringify(pluginVersion)} must use x.y.z format.`);
      }
    }
    if (typeof manifest.version === "string" && Object.hasOwn(versions, manifest.version)) {
      if (versions[manifest.version] !== manifest.minAppVersion) {
        errors.push("versions.json current-version entry must match manifest.minAppVersion.");
      }
    }
  }

  return errors;
}

export function validateReleaseBundle({ bundleText, bundlePath = "main.js" }) {
  const errors = [];
  if (typeof bundleText !== "string" || bundleText.length < 500) {
    errors.push(`${bundlePath} is missing or implausibly small.`);
    return errors;
  }
  if (!bundleText.includes("THIS IS A GENERATED/BUNDLED FILE BY ESBUILD")) {
    errors.push(`${bundlePath} is missing the production bundle banner.`);
  }
  if (/require\(["']\.\.?\//.test(bundleText)) {
    errors.push(`${bundlePath} contains a relative runtime require(), so it is not self-contained.`);
  }
  if (/sourceMappingURL\s*=/.test(bundleText)) {
    errors.push(`${bundlePath} contains a source-map reference; production releases must not ship source maps.`);
  }
  if (/\.test-build|tests\//.test(bundleText)) {
    errors.push(`${bundlePath} appears to contain test-harness paths.`);
  }
  if (!/require\(["']obsidian["']\)/.test(bundleText)) {
    errors.push(`${bundlePath} does not externalize the Obsidian API as expected.`);
  }
  if (/InvariantViolationError|__PLACEHOLDER_DEV_ASSERTIONS__|\bINV-00[1-9]\b/.test(bundleText)) {
    errors.push(`${bundlePath} contains development invariant machinery; production assertions must be compiled out.`);
  }
  return errors;
}

export function validateReleaseAssetTree(root) {
  const errors = [];
  const required = ["main.js", "manifest.json", "styles.css"];
  for (const name of required) {
    const full = path.join(root, name);
    if (!fs.existsSync(full) || !fs.statSync(full).isFile()) errors.push(`Required release asset is missing: ${name}`);
  }
  for (const forbidden of ["main.js.map", "data.json"]) {
    if (fs.existsSync(path.join(root, forbidden))) errors.push(`Forbidden release artifact exists: ${forbidden}`);
  }
  return errors;
}

export function assertNoErrors(label, errors) {
  if (errors.length === 0) return;
  const lines = errors.map((error) => `- ${error}`).join("\n");
  throw new Error(`${label} failed:\n${lines}`);
}

function requireString(object, key, errors) {
  if (typeof object[key] !== "string" || object[key].trim().length === 0) {
    errors.push(`manifest.${key} must be a non-empty string.`);
  }
}

function validateFundingUrl(value, errors) {
  if (typeof value === "string") {
    if (!isHttpUrl(value)) errors.push("manifest.fundingUrl must be an http(s) URL.");
    return;
  }
  if (!isPlainObject(value) || Object.keys(value).length === 0) {
    errors.push("manifest.fundingUrl must be a URL string or non-empty object of URL strings.");
    return;
  }
  for (const [label, url] of Object.entries(value)) {
    if (label.trim().length === 0 || !isHttpUrl(url)) errors.push("Every manifest.fundingUrl entry must have a label and http(s) URL.");
  }
}

function isHttpUrl(value) {
  if (typeof value !== "string") return false;
  try {
    const url = new URL(value);
    return url.protocol === "http:" || url.protocol === "https:";
  } catch {
    return false;
  }
}

function isPlainObject(value) {
  return value !== null && typeof value === "object" && !Array.isArray(value);
}

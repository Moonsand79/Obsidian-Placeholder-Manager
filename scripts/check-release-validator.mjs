import assert from "node:assert/strict";
import { validateReleaseBundle, validateReleaseMetadata } from "./release-validation.mjs";

const validManifest = {
  id: "placeholder-manager",
  name: "Placeholder Manager",
  version: "0.1.2",
  minAppVersion: "1.13.7",
  description: "Manage structured writing placeholders.",
  author: "Gawonii",
  isDesktopOnly: false,
};
const validPackage = { version: "0.1.2", main: "main.js", type: "module", private: true };
const validVersions = { "0.1.2": "1.13.7" };

assert.deepEqual(validateReleaseMetadata({ manifest: validManifest, versions: validVersions, pkg: validPackage }), []);

const badManifest = { ...validManifest, id: "Obsidian_Plugin", version: "v0.1.2", description: "bad" };
const badErrors = validateReleaseMetadata({ manifest: badManifest, versions: validVersions, pkg: validPackage });
assert.ok(badErrors.some((error) => error.includes("manifest.id")));
assert.ok(badErrors.some((error) => error.includes("manifest.version")));
assert.ok(badErrors.some((error) => error.includes("period")));
assert.ok(badErrors.some((error) => error.includes("package.json version")));

const validBundle = `/* THIS IS A GENERATED/BUNDLED FILE BY ESBUILD */\n${"x".repeat(600)}\nvar obsidian = require("obsidian");\n`;
assert.deepEqual(validateReleaseBundle({ bundleText: validBundle }), []);
assert.ok(validateReleaseBundle({ bundleText: `require("./src/main")${"x".repeat(600)}` }).length > 0);
const devAssertionBundle = `${validBundle}class InvariantViolationError {}\nconst code = "INV-004";\n`;
assert.ok(validateReleaseBundle({ bundleText: devAssertionBundle }).some((error) => error.includes("development invariant")));

console.log("Release validator self-tests OK.");
